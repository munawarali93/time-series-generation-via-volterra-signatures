"""Reproduce the lesson model and animate its learned ODE trajectories.

Run with the project's Python environment. Requires imageio-ffmpeg.
The original notebook and its figures are not modified.
"""
from pathlib import Path
import json

import imageio_ffmpeg
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import torch
from torch import nn

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "videos"
OUT.mkdir(exist_ok=True)
CHECKPOINT = OUT / "flow_matching_model.pt"
torch.set_num_threads(1)
torch.manual_seed(7)
centers = torch.tensor([[-2., -2.], [-2., 2.], [2., -2.], [2., 2.]])
sigma = 0.35


def sample_data(n):
    labels = torch.randint(4, (n,))
    return centers[labels] + sigma * torch.randn(n, 2)


x_train = sample_data(4096)
model = nn.Sequential(nn.Linear(3, 64), nn.SiLU(), nn.Linear(64, 64),
                      nn.SiLU(), nn.Linear(64, 2))
if CHECKPOINT.exists():
    model.load_state_dict(torch.load(CHECKPOINT, weights_only=True)["model_state_dict"])
    print("Loaded saved model", flush=True)
else:
    loss_fn = nn.MSELoss()
    optimizer = torch.optim.Adam(model.parameters(), lr=0.001)
    for step in range(5000):
        x1 = x_train[torch.randint(len(x_train), (256,))]
        x0 = torch.randn(256, 2)
        t = torch.rand(256, 1)
        xt = (1 - t) * x0 + t * x1
        target = x1 - x0
        prediction = model(torch.cat([xt, t], dim=1))
        loss = loss_fn(prediction, target)
        optimizer.zero_grad()
        loss.backward()
        optimizer.step()
        if (step + 1) % 1000 == 0:
            print(f"Training {step + 1}/5000, loss={loss.item():.4f}", flush=True)
    torch.save({"model_state_dict": model.state_dict(), "training_seed": 7,
                "training_updates": 5000}, CHECKPOINT)

model.eval()
torch.manual_seed(2026)
# Preserve the notebook's initial sample and reference draws.
z = torch.randn(5000, 2)
reference = sample_data(5000)
x = z[:2000].clone()
steps = 300
path = [x.numpy().copy()]
with torch.no_grad():
    for k in range(steps):
        t = torch.full((len(x), 1), k / steps)
        x = x + model(torch.cat([x, t], dim=1)) / steps
        path.append(x.numpy().copy())
path = np.stack(path)
assert np.isfinite(path).all()
np.savez_compressed(OUT / "flow_matching_trajectories.npz", path=path)

navy, blue, coral = "#15345C", "#2266B3", "#D6603C"
plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 13,
                     "text.color": navy, "axes.labelcolor": navy,
                     "xtick.color": navy, "ytick.color": navy})
fig = plt.figure(figsize=(12.8, 7.2), dpi=100, facecolor="white")
fig.text(.055, .94, "From Gaussian noise to a Gaussian mixture",
         fontsize=25, weight="bold")
fig.text(.055, .895, "Actual trajectories generated by the trained flow-matching model",
         fontsize=14, color="#526579")
ax = fig.add_axes([.07, .22, .50, .59])
ref = fig.add_axes([.66, .42, .28, .36])
for a in [ax, ref]:
    a.set(xlim=(-4.5, 4.5), ylim=(-4.5, 4.5), aspect="equal")
    a.set_xticks([-4, -2, 0, 2, 4])
    a.set_yticks([-4, -2, 0, 2, 4])
    a.spines[["top", "right"]].set_visible(False)
    a.spines[["bottom", "left"]].set_color("#B5C3D0")
    a.grid(alpha=.12)
    a.set_xlabel("Coordinate 1")
    a.set_ylabel("Coordinate 2")
points = ax.scatter(path[0, :, 0], path[0, :, 1], s=6, alpha=.45,
                    color=blue, edgecolors="none")
stage = ax.set_title("Starting distribution: Gaussian", fontsize=17, pad=12)
ref.scatter(reference[:2000, 0], reference[:2000, 1], s=5, alpha=.35,
            color=coral, edgecolors="none")
ref.set_title("Target GMM (reference)", fontsize=16, pad=12)
fig.text(.66, .265, "Four equally weighted Gaussian clusters\n"
         "Each coordinate has standard deviation 0.35",
         fontsize=12, linespacing=1.6)
fig.text(.66, .18, "The reference points do not guide sampling.\n"
         "Only the learned velocity moves the blue points.",
         fontsize=11, color="#526579", linespacing=1.6)
clock = fig.text(.075, .08, "t = 0.00", fontsize=20, weight="bold", color=blue)
fig.text(.25, .08, r"$X_{k+1}=X_k+\Delta t\,v_\theta(X_k,t_k)$", fontsize=19)
fig.text(.66, .08, "2,000 points  |  300 Euler steps", fontsize=12)

fps = 30
frame_indices = [0] * 30 + list(range(1, steps + 1)) + [steps] * 60
video = OUT / "gaussian_to_gmm.mp4"
writer = imageio_ffmpeg.write_frames(str(video), (1280, 720), fps=fps,
    codec="libx264", pix_fmt_in="rgb24", pix_fmt_out="yuv420p", quality=8,
    output_params=["-movflags", "+faststart"], ffmpeg_log_level="error")
writer.send(None)
try:
    for frame_no, index in enumerate(frame_indices):
        points.set_offsets(path[index])
        clock.set_text(f"t = {index / steps:.2f}")
        stage.set_text("Starting distribution: Gaussian" if index == 0 else
                       "Generated distribution at t = 1" if index == steps else
                       "Moving under the learned velocity")
        fig.canvas.draw()
        rgb = np.asarray(fig.canvas.buffer_rgba())[:, :, :3].copy()
        writer.send(rgb)
        if index in [0, 150, 300] and (frame_no == 0 or frame_no == index + 29):
            fig.savefig(OUT / f"preview_t{index:03d}.png", dpi=100)
        if frame_no % 90 == 0:
            print(f"Encoded {frame_no}/{len(frame_indices)} frames", flush=True)
finally:
    writer.close()
plt.close(fig)
distances, groups = torch.cdist(torch.from_numpy(path[-1]), centers).min(dim=1)
metadata = {"training_seed": 7, "training_updates": 5000, "sampling_seed": 2026,
            "points": len(x), "euler_steps": steps, "fps": fps,
            "frames": len(frame_indices), "duration_seconds": len(frame_indices) / fps,
            "resolution": [1280, 720],
            "nearest_center_shares": (torch.bincount(groups, minlength=4) / len(x)).tolist(),
            "rms_distance_to_nearest_center": distances.square().mean().sqrt().item(),
            "torch_version": str(torch.__version__),
            "note": "Learned ODE output, not interpolation to selected GMM endpoints."}
(OUT / "video_metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
print(f"Saved {video}", flush=True)
